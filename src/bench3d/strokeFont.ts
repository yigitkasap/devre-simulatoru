const FOLD: Record<string, string> = { Ç: 'C', Ğ: 'G', İ: 'I', I: 'I', Ö: 'O', Ş: 'S', Ü: 'U', '−': '-', '–': '-', '·': '.', '×': 'X' };

/** Yazının yazı tipindeki karşılığı (büyük harf, Türkçe harfler sadeleşmiş); bilinmeyen karakter boşluk. */
export function foldText(text: string): string {
  return [...text.toLocaleUpperCase('tr')]
    .map((c) => FOLD[c] ?? c)
    .map((c) => (c in GLYPHS ? c : ' '))
    .join('');
}

/** Yazının çizgileri (kart koordinatı, y aşağı): (cx, cy) yazının ortası, `height` harf yüksekliği. */
export function textStrokes(text: string, cx: number, cy: number, height: number): Array<Array<readonly [number, number]>> {
  const s = foldText(text);
  const u = height / 6;
  const width = s.length * 6 * u - 2 * u;
  const left = cx - width / 2;
  const base = cy + height / 2;
  const out: Array<Array<readonly [number, number]>> = [];
  [...s].forEach((c, i) => {
    for (const line of GLYPHS[c]!) out.push(line.map(([x, y]) => [left + (i * 6 + x) * u, base - y * u] as const));
  });
  return out;
}
